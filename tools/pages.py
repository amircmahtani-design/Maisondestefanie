# -*- coding: utf-8 -*-
"""Build every page of the site out of one shell and one file of sections.

  tools/shell.html      the head, the header, the footer, the dock, the
                        stage and the drawer, with <!--PAGE--> where the
                        content of a page goes
  tools/sections.html   every section of the site, each under its own
                        ══ banner ══ comment

Run after changing either:

    python3 tools/pages.py

It writes index.html, maison.html, bespoke.html, story.html,
creations.html and visit.html. Those files are committed and Netlify
publishes the repository as it stands — there is no build step at deploy
time, and there is nothing to install to run this.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHELL = os.path.join(ROOT, 'tools', 'shell.html')
SECTIONS = os.path.join(ROOT, 'tools', 'sections.html')

# file, content key, name in the <h1>, the sections it carries in order.
# A content key of None means the page writes its own first screen.
PAGES = [
    ('index.html', None, None,
     ['THE HERO', 'HER WORD', 'A MEMORY, DISTILLED', 'THE FIVE DOORS']),
    ('maison.html', 'maison', 'The Maison',
     ['HER WORDS', '03 · THE BENCH', 'A BREATH']),
    ('bespoke.html', 'bespoke', 'Bespoke Experience',
     ['THE SESSION', '04 · COMPOSED BY HAND', '05 · BOTTLED AND SEALED']),
    ('story.html', 'story', 'The Story',
     ['THE STORY', 'GUEST BOOK']),
    ('creations.html', 'creations', 'Creations',
     ['THE SHELF']),
    ('visit.html', 'visit', 'Visit',
     ['06 · VISIT', 'GOOD TO KNOW']),
]

# The home page's first screen is the film: four locked plates with the
# petals, ripples, vapour and drops animated over them as their own
# layers. It is the only page that loads those two files, and the only
# one that can name its opening image in advance — which it does at both
# shapes, with the same media query the player switches on.
FILM_HEAD = (
    '<link rel="preload" as="image" href="/assets/hero/plate-1-wide.webp"\n'
    '      media="(min-aspect-ratio: 1/1)" fetchpriority="high">\n'
    '<link rel="preload" as="image" href="/assets/hero/plate-1-upright.webp"\n'
    '      media="(max-aspect-ratio: 1/1)" fetchpriority="high">\n'
    '<link rel="stylesheet" href="/assets/hero-film.css?v=8">')

FILM_FOOT = (
    '<script type="module">\n'
    '  import { mountFilmHero } from "/assets/hero-film.js?v=8";\n'
    '  mountFilmHero(document.querySelector(".filmhero"));\n'
    '</script>')

BANNER = (
    '<!-- ════════════════════════════════════════════════════════════════\n'
    '     GENERATED — do not edit this file by hand. Your change would be\n'
    '     overwritten the next time anyone runs the script.\n'
    '     The shell is tools/shell.html, the sections are\n'
    '     tools/sections.html, and the script is tools/pages.py.\n'
    '     ════════════════════════════════════════════════════════════════ -->\n')


def first_screen(key, title):
    """A page opens on a picture of its own, named in the Studio."""
    slot = 'page' + key.capitalize()
    key_cap = key.capitalize()
    return (
        f'<!-- ══════════════ THE FIRST SCREEN ══════════════ -->\n'
        f'<section class="phero" id="top">\n'
        f'  <figure class="phero-pic" data-phero="{key}" aria-hidden="true"></figure>\n'
        f'  <div class="phero-in">\n'
        f'    <p class="phero-eyebrow" data-t="page{key_cap}.eyebrow"></p>\n'
        f'    <h1 data-t="page{key_cap}.title">{title}</h1>\n'
        f'    <p class="phero-lede" data-t="page{key_cap}.lede"></p>\n'
        f'  </div>\n'
        f'</section>\n')


def canonical(head, filename):
    """Each page points search engines at itself, not at the home page."""
    home = 'https://lamaisondestefanie.com/'
    here = home if filename == 'index.html' else home + filename
    head = head.replace(f'<link rel="canonical" href="{home}">',
                        f'<link rel="canonical" href="{here}">')
    head = head.replace(f'<link rel="alternate" hreflang="en" href="{home}">',
                        f'<link rel="alternate" hreflang="en" href="{here}">')
    head = head.replace(f'<link rel="alternate" hreflang="el" href="{home}?lang=el">',
                        f'<link rel="alternate" hreflang="el" href="{here}?lang=el">')
    head = head.replace(f'<link rel="alternate" hreflang="x-default" href="{home}">',
                        f'<link rel="alternate" hreflang="x-default" href="{here}">')
    return head


def main():
    shell = open(SHELL, encoding='utf-8').read()
    body = open(SECTIONS, encoding='utf-8').read()

    marks = [(m.start(), m.group(1).strip())
             for m in re.finditer(r'<!-- ═+ (.*?) ═+ -->', body)]
    chunk = {}
    for i, (pos, name) in enumerate(marks):
        end = marks[i + 1][0] if i + 1 < len(marks) else len(body)
        chunk[name] = body[pos:end].rstrip() + '\n'

    for filename, key, title, wanted in PAGES:
        missing = [w for w in wanted if w not in chunk]
        if missing:
            raise SystemExit(f'{filename}: tools/sections.html has no {missing}')

        page = canonical(shell, filename)
        page = page.replace('<!--HEAD-->', FILM_HEAD if filename == 'index.html' else '')
        page = page.replace('<!--FOOT-->', FILM_FOOT if filename == 'index.html' else '')
        if filename != 'index.html':
            # the curtain is the way in through the front door, and plays
            # there only
            page = re.sub(r'<!-- ═+ THE CURTAIN.*?\n</div>\n', '', page, flags=re.S)
            page = page.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + BANNER, 1)
            content = first_screen(key, title) + '\n'
        else:
            page = page.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n' + BANNER, 1)
            content = ''

        content += '\n'.join(chunk[w] for w in wanted)
        out = page.replace('<!--PAGE-->', content.rstrip() + '\n')
        open(os.path.join(ROOT, filename), 'w', encoding='utf-8').write(out)
        print(f'{filename:16} {len(out)//1024:3} KB   {", ".join(wanted)}')


if __name__ == '__main__':
    main()
